"""Build guarded native text from editable glyph/string sources; never write a ROM."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys
import zipfile

ROM_SHA = '98d210dcbd1c5d836aa5bbf018eb26e971711b69b4423187bbb72178d5da9a92'
REFERENCE_SHA = 'a143fb582956ce1f2214c0122a6cdd1f832bc82fb598c4d8a6b21102ccaab906'


def encode_entries(source):
    if source['format'] != 1 or source['language'] != 'en':
        raise ValueError('Unsupported text source format/language')
    glyphs = {char: bytes.fromhex(value) for char, value in source['glyphs'].items()}
    if any(len(char) != 1 or len(value) != 1 or value[0] < 32 or value[0] > 126
           for char, value in glyphs.items()):
        raise ValueError('Glyph mappings must be printable single-byte native codes')
    entries = []
    ids = set()
    for entry in source['entries']:
        if entry['id'] in ids:
            raise ValueError('Duplicate text id: ' + entry['id'])
        ids.add(entry['id'])
        try:
            data = b''.join(glyphs[char] for char in entry['text'])
        except KeyError as exc:
            raise ValueError(f"Unsupported glyph {exc} in {entry['id']}") from exc
        capacity = entry['capacity']
        if not isinstance(capacity, int) or capacity < 1 or len(data) > capacity:
            raise ValueError('Text exceeds native capacity: ' + entry['id'])
        if entry['padding'] not in ('space', 'nul'):
            raise ValueError('Unsupported padding')
        data += (b' ' if entry['padding'] == 'space' else b'\0') * (capacity - len(data))
        off = int(entry['offset'], 0)
        if off < 0:
            raise ValueError('Negative offset')
        entries.append((off, data))
    entries.sort()
    for (off, data), (next_off, _) in zip(entries, entries[1:]):
        if off + len(data) > next_off:
            raise ValueError('Overlapping text spans')
    if not entries:
        raise ValueError('Empty text plan')
    return entries


def main():
    root = Path(__file__).resolve().parents[1]
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--rom', type=Path, default=root/'roms/sd_gundam.vb')
    p.add_argument('--framework', type=Path, required=True)
    p.add_argument('--check-reference', action='store_true')
    args = p.parse_args()
    rom = args.rom.read_bytes()
    if hashlib.sha256(rom).hexdigest() != ROM_SHA:
        raise ValueError('Expected original Japanese cartridge')
    source = json.loads((root/'translations/english.json').read_text(encoding='utf8'))
    entries = encode_entries(source)
    sys.path.insert(0, str(args.framework.resolve()))
    from recompiler.v810.analysis import RomImage
    image = RomImage.from_bytes(rom)
    dispatch = (root/'generated/sd_gundam_dispatch.c').read_text(encoding='utf8')
    pcs = {int(pc, 16) for pc in re.findall(r'\{0x([0-9A-F]+)u, vb_fn_', dispatch)}
    if not pcs:
        raise ValueError('Missing generated instruction table')
    spans = [(off, off+len(data)) for off, data in entries]
    for pc in pcs:
        ins = image.decode_at_va(pc)
        off = image.va_to_offset(pc)
        if ins is not None and any(off < b and off+ins.size > a for a, b in spans):
            raise ValueError(f'Text overlaps generated instruction {pc:08x}')
    target = bytearray(rom)
    header = ['/* Generated by tools/build_translation.py; do not edit. */',
              '#pragma once', '#include "rom_patch.h"']
    rows = []
    for i, (off, data) in enumerate(entries):
        if off+len(data) > len(rom):
            raise ValueError('Text exceeds cartridge bounds')
        original = rom[off:off+len(data)]
        for name, payload in [('source', original), ('target', data)]:
            values = ','.join(f'0x{b:02x}' for b in payload)
            header.append(f'static const uint8_t text_{name}_{i}[] = {{{values}}};')
        rows.append(f'    {{0x{off:x}u,{len(data)}u,text_source_{i},text_target_{i}}},')
        target[off:off+len(data)] = data
    target_sha = hashlib.sha256(target).hexdigest()
    if args.check_reference and target_sha != REFERENCE_SHA:
        raise ValueError('Editable text does not reproduce the reference IPS image')
    header += ['static const VbRomDataPatch sd_gundam_text[] = {', *rows, '};',
               f'static const unsigned sd_gundam_text_count = {len(entries)};', '']
    generated = root/'generated/sd_gundam_translation.h'
    generated.write_text('\n'.join(header), encoding='utf8', newline='\n')
    dist = root/'dist'; dist.mkdir(exist_ok=True)
    with zipfile.ZipFile(dist/'sd-gundam-english-0.1.0.vbmod', 'w', zipfile.ZIP_DEFLATED) as z:
        z.write(root/'mods/english/manifest.toml', 'manifest.toml')
        z.write(root/'translations/english.json', 'source/english.json')
    print(json.dumps({'entries': len(entries), 'changed_bytes': sum(a != b for a,b in zip(rom,target)),
                      'generated_instructions_audited': len(pcs), 'code_overlaps': 0,
                      'translated_image_sha256': target_sha,
                      'matches_reference': target_sha == REFERENCE_SHA}, indent=2))


if __name__ == '__main__':
    main()
